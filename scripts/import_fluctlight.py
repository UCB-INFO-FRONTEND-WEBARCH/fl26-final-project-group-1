"""Import a Fluctlight browser bundle: the Lite Pro model, its meshes, the policies, and their parity fixtures.

Fluctlight (tracker/ppo) writes the bundle with ``uv run export-browser``. This copies it into
``public/assets/lite_pro`` and ``tests/fixtures/fluctlight``, checks every policy hash against the bundle index,
writes ``manifest.json``, and generates ``src/policy_constants.js``. Run ``npm run assets:visuals`` afterwards to
rebuild the render meshes from the new robot.xml.

    python3 scripts/import_fluctlight.py /path/to/bundle
"""

import argparse
import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / 'public/assets/lite_pro'
FIXTURES = ROOT / 'tests/fixtures/fluctlight'
# Kept across imports: the robot description's license notice and the render-only meshes.
KEPT = {'ROBOT_LICENSE', 'visuals.json', 'visuals.bin'}
# The policies the controller switches between (src/robot_controller.js); walk_stairs and sit are optional.
REQUIRED = ('walk', 'getup_supine', 'getup_prone')


def sha256(path: Path) -> str:
  return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument('bundle', type=Path)
  args = parser.parse_args()
  index = json.loads((args.bundle / 'index.json').read_text())
  missing = [name for name in REQUIRED if name not in index['policies']]
  if missing:
    raise ValueError(f'The bundle lacks the policies {missing}.')

  for path in DESTINATION.iterdir():
    if path.name in KEPT:
      continue
    shutil.rmtree(path) if path.is_dir() else path.unlink()
  shutil.copy2(args.bundle / 'robot.xml', DESTINATION / 'robot.xml')
  shutil.copytree(args.bundle / 'meshes', DESTINATION / 'meshes')
  (DESTINATION / 'policies').mkdir()
  FIXTURES.mkdir(parents=True, exist_ok=True)
  for path in FIXTURES.iterdir():
    path.unlink()
  for path in (args.bundle / 'fixtures').iterdir():
    shutil.copy2(path, FIXTURES / path.name)

  contracts = {}
  for name, entry in index['policies'].items():
    contract = json.loads((args.bundle / entry['contract']).read_text())
    onnx = args.bundle / 'policies' / contract['onnx']
    if sha256(onnx) != contract['onnx_sha256'] or contract['onnx_sha256'] != entry['onnx_sha256']:
      raise ValueError(f'{name}: the ONNX file differs from its contract.')
    shutil.copy2(onnx, DESTINATION / 'policies' / contract['onnx'])
    shutil.copy2(args.bundle / entry['contract'], DESTINATION / 'policies' / f'{name}.json')
    motion = contract.get('motion')
    if motion:
      # A sit policy's chair clips (BONES-SEED, retargeted to Lite Pro), which it tracks at run time.
      clips = args.bundle / 'policies' / motion['file']
      if sha256(clips) != motion['sha256']:
        raise ValueError(f'{name}: the clips differ from their contract.')
      shutil.copy2(clips, DESTINATION / 'policies' / motion['file'])
    contracts[name] = contract

  walk = contracts['walk']
  for name, contract in contracts.items():
    for key in ('joint_names', 'physics_dt', 'policy_dt'):
      if contract[key] != walk[key]:
        raise ValueError(f'{name}: {key} differs from the walking policy.')

  files = []
  # The render meshes derive from robot.xml (npm run assets:visuals), and visuals.json records their hash.
  for path in sorted(DESTINATION.rglob('*')):
    if path.is_file() and path.name not in ('manifest.json', 'visuals.json', 'visuals.bin'):
      files.append({'file': path.relative_to(DESTINATION).as_posix(), 'bytes': path.stat().st_size, 'sha256': sha256(path)})
  manifest = {
    'source': 'https://github.com/berkeley-humanoids/Fluctlight (tracker/ppo, export-browser)',
    'commit': index.get('fluctlight_commit', ''),
    'robot': index['robot'],
    'policies': {name: {k: entry[k] for k in ('task', 'checkpoint', 'onnx_sha256')} for name, entry in index['policies'].items()},
    'files': files,
  }
  (DESTINATION / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')

  constants = {
    'joint_names': walk['joint_names'],
    'default_joint_pos': walk['default_joint_pos'],
    'timestep': walk['physics_dt'],
    'decimation': round(walk['policy_dt'] / walk['physics_dt']),
    'step_dt': walk['policy_dt'],
    'policies': {name: f'policies/{name}.json' for name in contracts},
    'checkpoints': {name: contract['checkpoint'] for name, contract in contracts.items()},
    'clips': {name: f"policies/{c['motion']['file']}" for name, c in contracts.items() if c.get('motion')},
    'root_height_walk': walk['command']['root_height_walk'],
    'root_height_stand': walk['command']['root_height_stand'],
  }
  (ROOT / 'src/policy_constants.js').write_text(
    '// Generated by scripts/import_fluctlight.py from the Fluctlight browser bundle.\n'
    'export const POLICY = ' + json.dumps(constants, indent=2) + ';\n')
  print(f'Imported {", ".join(f"{n} ({c["checkpoint"]})" for n, c in contracts.items())}')


if __name__ == '__main__':
  main()
