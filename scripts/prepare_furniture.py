"""Build compound convex colliders from the playground's selected IKEA models."""

import concurrent.futures
import hashlib
import json
import multiprocessing
import os
from pathlib import Path
import subprocess

os.environ.setdefault("OMP_NUM_THREADS", "2")

import coacd
import numpy as np
import trimesh

ROOT = Path(__file__).resolve().parents[1]
LIBRARY = ROOT / "local_assets" / "ikea"
SETTINGS = {
  "threshold": 0.01, "real_metric": True, "max_convex_hull": 32,
  "preprocess_resolution": 80, "resolution": 2000, "mcts_nodes": 10,
  "mcts_iterations": 50, "seed": 0,
}


def prepare(article):
  source = LIBRARY / "raw" / article / "model.glb"
  digest = hashlib.sha256(source.read_bytes()).hexdigest()
  cache = LIBRARY / "collisions" / f"{article}.json"
  if cache.is_file():
    result = json.loads(cache.read_text())
    if result["sha256"] == digest and result["settings"] == SETTINGS and result.get("input_frame") == "Y-up":
      return article, result
  scene = trimesh.load_scene(source, process=False)
  visual = scene.to_mesh()
  bounds = visual.bounds
  origin = [(bounds[0, 0] + bounds[1, 0]) / 2, bounds[0, 1], (bounds[0, 2] + bounds[1, 2]) / 2]
  coacd.set_log_level("error")
  print(f"Preparing {article}", flush=True)
  parts = coacd.run_coacd(coacd.Mesh(visual.vertices, visual.faces), **SETTINGS)
  hulls = []
  for points, faces in parts:
    points = (points - origin)[:, [0, 2, 1]]
    points[:, 1] *= -1
    hulls.append(np.round(points, 6).tolist())
  result = {
    "sha256": digest,
    "settings": SETTINGS,
    "input_frame": "Y-up",
    "origin": np.round(origin, 7).tolist(),
    "size": np.round((bounds[1] - bounds[0])[[0, 2, 1]], 7).tolist(),
    "triangles": len(visual.faces),
    "hulls": hulls,
  }
  cache.parent.mkdir(parents=True, exist_ok=True)
  cache.write_text(json.dumps(result))
  print(f"{article}: {len(visual.faces):,} visual triangles, {len(parts)} convex colliders", flush=True)
  return article, result


def main():
  layout = json.loads(subprocess.check_output([
    "node", "--input-type=module", "--eval",
    "import {SCENE_FURNITURE} from './src/furniture_layout.js'; process.stdout.write(JSON.stringify(SCENE_FURNITURE));",
  ], cwd=ROOT))
  articles = sorted({item["article"] for item in layout})
  with concurrent.futures.ProcessPoolExecutor(max_workers=2, mp_context=multiprocessing.get_context("spawn")) as pool:
    assets = dict(pool.map(prepare, articles))
  output = "// Generated by scripts/prepare_furniture.py. Metres, centred XY, grounded, Z up.\n"
  output += "export const FURNITURE_ASSETS = " + json.dumps(assets, separators=(",", ":")) + ";\n"
  (ROOT / "src" / "furniture_assets.js").write_text(output)
  print(f"Prepared {len(assets)} assets for {len(layout)} furniture placements.")


if __name__ == "__main__":
  main()
