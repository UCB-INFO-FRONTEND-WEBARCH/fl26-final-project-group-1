"""Generate metric colliders for the catalog items used by the sitting policy."""
import json
from prepare_furniture import ROOT, prepare


def main():
  assets = dict(prepare(article) for article in ['90434310', '69499704'])
  output = '// Generated by scripts/prepare_seating.py. Grounded, centred XY, metres, Z up.\n'
  output += 'export const SEATING_ASSETS = ' + json.dumps(assets, separators=(',', ':')) + ';\n'
  (ROOT / 'src/seating_assets.js').write_text(output)


if __name__ == '__main__':
  main()
