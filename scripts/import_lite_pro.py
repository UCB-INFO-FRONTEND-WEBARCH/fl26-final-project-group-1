"""Import the exact Lite Pro S3 browser checkpoint, meshes, and controller constants."""

import argparse
import base64
import hashlib
import json
from pathlib import Path
from urllib.request import Request, urlopen
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / 'public/assets/lite_pro'
COMMIT = '07396764422e274e4316719f9dfb1fd734e9a516'
BASE = ('https://3f1123b8-917d-4021-97d5-7e93a5cd0100.frame.claudeusercontent.com/'
        '_f/1793787187-3873/demo/')
EXPECTED = {
  'policy.onnx': 'f0ff3ef686b6fae8690ffc5a9a8003c8e45c74830c2287fd90f25258563c7a28',
  'meshes.bin': '1d5bb04986a641c3ee3bac8e188408ab581308f82bd5a0b6a8ea2fc76d15d5fa',
  'constants.json': 'c8f0363249b7c80f5cbcc77eeeab7dc5786a0409c85cf69c15d32ef686a396b1',
  'core.js': '5cca56cdf4917edc5cab91912a149a5f761e1cbc64b44363c7db980bb9a4add6',
  'scene.xml': 'fd319455c187b8840e42c7385e1d989d9ccb65e67877b42d16808ce218ce87eb',
}


def download(url):
  request = Request(url, headers={'User-Agent': 'Mozilla/5.0', 'Referer': 'https://claude.ai/'})
  with urlopen(request, timeout=60) as response:
    return response.read()


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument('--source-dir', type=Path, help='Previously downloaded and decoded demo export')
  args = parser.parse_args()
  DESTINATION.mkdir(parents=True, exist_ok=True)
  (DESTINATION / 'meshes').mkdir(exist_ok=True)
  files = []

  def write(name, content):
    (DESTINATION / name).write_bytes(content)
    files.append({'file': name, 'bytes': len(content), 'sha256': hashlib.sha256(content).hexdigest()})

  def read(name):
    if args.source_dir:
      content = (args.source_dir / name).read_bytes()
    elif name in ('policy.onnx', 'meshes.bin'):
      encoded = 'policy.b64.txt' if name == 'policy.onnx' else 'meshes.b64.txt'
      content = base64.b64decode(download(BASE + encoded).strip(), validate=True)
    else:
      content = download(BASE + name)
    if name in EXPECTED and hashlib.sha256(content).hexdigest() != EXPECTED[name]:
      raise ValueError(f'{name}: source differs from the pinned browser checkpoint')
    return content

  # These attribution files ship in Git, including for an offline re-import.
  licenses = [
    ('LICENSE', '0afbf192c4dfb4f8ffd7783eb61a8829d1ebee17d3f2b1dc1b0bdb62838f2a93'),
    ('ROBOT_LICENSE', '9876efadd7f64d2ac72dcf0ac8276f7fe5fadf73b6e417897aab663a8909c0ad'),
  ]
  for name, expected in licenses:
    content = (DESTINATION / name).read_bytes()
    if hashlib.sha256(content).hexdigest() != expected:
      raise ValueError(f'{name}: restore the bundled attribution notice from Git')
    write(name, content)

  write('policy.onnx', read('policy.onnx'))
  constants_bytes = read('constants.json')
  constants = json.loads(constants_bytes)
  assert len(constants['joint_names']) == 34
  write('constants.json', constants_bytes)
  runtime = {key: value for key, value in constants.items() if key != 'meshes'}
  (ROOT / 'src/policy_constants.js').write_text(
    '// Generated by scripts/import_lite_pro.py from the pinned S3 browser export.\n'
    'export const POLICY = ' + json.dumps(runtime, indent=2) + ';\n')
  blob = read('meshes.bin')
  for name, offset, size in constants['meshes']:
    if Path(name).name != name or offset < 0 or size <= 0 or offset + size > len(blob):
      raise ValueError('Invalid mesh archive entry')
    write('meshes/' + name, blob[offset:offset + size])
  (DESTINATION / 'reference').mkdir(exist_ok=True)
  write('reference/core.js', read('core.js'))
  scene_bytes = read('scene.xml')
  scene = ET.fromstring(scene_bytes)
  world = scene.find('worldbody')
  # Retain the complete trained robot; the apartment supplies terrain and lighting.
  for child in list(world):
    if child.tag != 'body' or child.get('name') != 'robot/pelvis':
      world.remove(child)
  scene.set('model', 'Berkeley Lite Pro S3')
  write('robot.xml', ET.tostring(scene, encoding='utf-8'))
  contract = {
    'source': 'https://github.com/berkeley-humanoids/instinctmj', 'commit': COMMIT,
    'artifact': 'https://claude.ai/artifact/8nh5Z94mUcC7iCdg3cDGpo', 'asset_base': BASE,
    'checkpoint': constants['checkpoint_label'], 'license': 'CC-BY-NC-4.0',
    'robot_license': 'MIT', 'observation_size': 2798, 'action_size': 34,
    'physics_dt': constants['timestep'], 'control_decimation': constants['decimation'],
    'sha256': EXPECTED['policy.onnx'],
    'constants_sha256': hashlib.sha256(constants_bytes).hexdigest(),
    'source_scene_sha256': EXPECTED['scene.xml'],
    'export': 'Unchanged upstream velocity-mode ONNX, including normalizer, goal mask, depth encoder, and actor',
  }
  write('contract.json', (json.dumps(contract, indent=2) + '\n').encode())
  manifest = {'commit': COMMIT, 'source': contract['source'], 'files': files}
  (DESTINATION / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
  print(f'Imported {contract["checkpoint"]}: 34 joints, {len(constants["meshes"])} meshes')


if __name__ == '__main__':
  main()
